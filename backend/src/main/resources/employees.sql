CREATE TABLE IF NOT EXISTS departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (length(btrim(name)) BETWEEN 1 AND 100),
    parent_department_id BIGINT,
    head_employee_number TEXT
);

ALTER TABLE employees
    ADD COLUMN IF NOT EXISTS department_id BIGINT,
    ADD COLUMN IF NOT EXISTS job_title TEXT,
    ADD COLUMN IF NOT EXISTS hired_on DATE,
    ADD COLUMN IF NOT EXISTS employment_type TEXT,
    ADD COLUMN IF NOT EXISTS manager_employee_number TEXT;

ALTER TABLE employees DROP CONSTRAINT IF EXISTS employees_employment_type;
ALTER TABLE employees ADD CONSTRAINT employees_employment_type
    CHECK (employment_type IS NULL OR employment_type IN ('regular', 'part_time', 'fixed_term', 'intern'));

ALTER TABLE employees
    ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'employee';

ALTER TABLE employees DROP CONSTRAINT IF EXISTS employees_role;
ALTER TABLE employees ADD CONSTRAINT employees_role
    CHECK (role IN ('admin', 'manager', 'employee'));

ALTER TABLE employees DROP CONSTRAINT IF EXISTS employees_manager_not_self;
ALTER TABLE employees ADD CONSTRAINT employees_manager_not_self
    CHECK (manager_employee_number IS NULL OR manager_employee_number <> employee_number);

ALTER TABLE employees ADD COLUMN IF NOT EXISTS born_on DATE;

UPDATE employees
SET born_on = (hired_on - make_interval(years => 22 + (abs(hashtext(employee_number)::bigint) % 16)::int,
                                        days => (abs(hashtext(employee_number || ':born')::bigint) % 300)::int))::date
WHERE born_on IS NULL AND hired_on IS NOT NULL AND employment_type IS DISTINCT FROM 'intern';

UPDATE employees
SET born_on = (hired_on - make_interval(years => 20 + (abs(hashtext(employee_number)::bigint) % 3)::int,
                                        days => (abs(hashtext(employee_number || ':born')::bigint) % 200)::int))::date
WHERE born_on IS NULL AND hired_on IS NOT NULL AND employment_type = 'intern';

INSERT INTO departments (name)
SELECT DISTINCT btrim(department)
FROM employees
WHERE length(btrim(department)) > 0
ON CONFLICT (name) DO NOTHING;

UPDATE employees AS employee
SET department_id = department.department_id
FROM departments AS department
WHERE employee.department_id IS NULL
  AND department.name = btrim(employee.department);
